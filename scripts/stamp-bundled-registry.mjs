#!/usr/bin/env node
// Stamp the bundled registry's publish time into the scanner source.
//
// A pinned scanner ships registries/llm-deprecations.json inside its tag. This
// stamp is what lets the scanner grade that bundled copy by AGE exactly like a
// downloaded snapshot (src/registry/freshRegistry.ts): on release day it is as
// fresh as a snapshot published the same moment; two weeks on, it is stale and
// the audit says so instead of claiming "no exposure" on old knowledge. It is
// also the ROLLBACK FLOOR — a downloaded snapshot older than this stamp is
// refused, so a replayed old (signed) snapshot cannot hide a newer retirement.
//
// RELEASE CHECKLIST: run this right before tagging, after the registry is
// validated (`npm run validate:registry`), and commit the generated file:
//
//   node scripts/stamp-bundled-registry.mjs
//
// MENDR_STAMP_AT=<ISO> overrides the clock for reproducible builds.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const registryPath = join(root, 'registries', 'llm-deprecations.json');
const outPath = join(root, 'src', 'registry', 'bundledStamp.ts');

const bytes = readFileSync(registryPath);
const entries = JSON.parse(bytes.toString('utf8'));
if (!Array.isArray(entries)) throw new Error(`${registryPath} must be a JSON array`);
// Mirrors registryVersionOf() in src/registry/manifest.ts: sha256: + 16 hex.
const version = 'sha256:' + createHash('sha256').update(bytes).digest('hex').slice(0, 16);
const rawAt = process.env.MENDR_STAMP_AT ?? new Date().toISOString();
if (Number.isNaN(Date.parse(rawAt))) throw new Error(`MENDR_STAMP_AT is not a parseable timestamp: ${rawAt}`);
const at = new Date(rawAt).toISOString().replace(/\.\d{3}Z$/, 'Z');

const out = `// GENERATED by scripts/stamp-bundled-registry.mjs — do not edit by hand.
//
// When the registry bundled into THIS build was stamped as current (the
// release checklist runs the stamp right before tagging). The scanner grades
// the bundled registry's age from it, and refuses any downloaded snapshot
// published before it (rollback floor). See src/registry/freshRegistry.ts.

/** ISO-8601 UTC. */
export const BUNDLED_PUBLISHED_AT = '${at}';
/** Content hash of registries/llm-deprecations.json at stamp time (informational). */
export const BUNDLED_REGISTRY_VERSION = '${version}';
/** Entries in the bundled registry at stamp time (informational). */
export const BUNDLED_ENTRY_COUNT = ${entries.length};
`;
writeFileSync(outPath, out, 'utf8');
console.log(`stamped ${at} (${version}, ${entries.length} entries) → src/registry/bundledStamp.ts`);
